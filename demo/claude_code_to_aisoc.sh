#!/usr/bin/env bash
#
# Send Claude Code's own logs (prompts, tool use, Bash commands, file edits,
# model requests) into AiSOC through its OpenTelemetry logs receiver.
#
#   ./demo/claude_code_to_aisoc.sh        # run from the AiSOC folder, with AiSOC up
#   source demo/claude-code.env && claude # then use Claude Code as normal
#
# What it does (safe to re-run):
#   1. switches on AiSOC's OTLP logs receiver (off by default)
#   2. mints a token for it (template "otlp-logs")
#   3. installs Claude Code if it is missing
#   4. writes demo/claude-code.env with the telemetry settings
#
# To browse the events in the console (Hunt / Explore), AiSOC must run with its
# event lake: `make up-full`. With plain `make up` they are received but only
# rule matches become visible (as alerts).
set -euo pipefail

cd "$(dirname "${BASH_SOURCE[0]}")/.."

say()  { echo; echo "== $* =="; }
note() { echo "   $*"; }
die()  { echo "ERROR: $*" >&2; exit 1; }

command -v docker >/dev/null || die "docker is not available"
docker info >/dev/null 2>&1 || die "Docker is not running. Start it: bash .devcontainer/start-docker.sh"
command -v jq >/dev/null || die "jq is required"

COMPOSE=(docker compose -f docker-compose.yml)
[[ -f docker-compose.ports.yml ]] && COMPOSE+=(-f docker-compose.ports.yml)

say "1. Switching on AiSOC's OpenTelemetry receiver"
# --no-deps: only the ingest service is recreated; nothing else is touched.
"${COMPOSE[@]}" -f demo/docker-compose.otlp.yml up -d --no-deps ingest-worker >/dev/null 2>&1 \
  || die "could not restart the ingest service (is AiSOC up? run: make up-full)"
port="$("${COMPOSE[@]}" port ingest-worker 8080 2>/dev/null | sed -E 's/.*:([0-9]+)$/\1/' || true)"
INGEST="http://localhost:${port:-8081}"
for _ in $(seq 1 60); do curl -sf "$INGEST/health" >/dev/null && break; sleep 2; done
curl -sf "$INGEST/health" >/dev/null || die "AiSOC ingest did not come back on $INGEST"
note "receiver: $INGEST/v1/logs"

say "2. Minting a token for it"
API_TOKEN="$("${COMPOSE[@]}" run --rm -T api python -m app.scripts.mint_api_token --quiet)" \
  || die "could not mint an API token (is AiSOC fully up? try: make doctor)"
out="$(curl -sS -X POST "http://localhost:8000/api/v1/inbox/tokens" \
  -H "Authorization: Bearer $API_TOKEN" -H 'Content-Type: application/json' \
  -d '{"template_id": "otlp-logs", "label": "claude-code"}')"
OTLP_TOKEN="$(jq -r '.token // empty' <<<"$out")"
[[ -n "$OTLP_TOKEN" ]] || die "AiSOC did not return a token: $out"
code="$(curl -s -o /dev/null -w '%{http_code}' -X POST "$INGEST/v1/logs" -H "X-Inbox-Token: $OTLP_TOKEN" \
  -H 'Content-Type: application/json' -d '{"resourceLogs":[]}')"
[[ "$code" == 200 ]] || die "the receiver refused a test batch (HTTP $code)"
note "token works (test batch accepted)"

say "3. Claude Code"
if ! command -v claude >/dev/null; then
  note "installing Claude Code..."
  npm install -g @anthropic-ai/claude-code >/dev/null
fi
note "$(claude --version)"

say "4. Writing demo/claude-code.env"
cat > demo/claude-code.env <<ENV
# Generated by demo/claude_code_to_aisoc.sh. Holds a live token: do not commit.
# Usage:  source demo/claude-code.env && claude
export CLAUDE_CODE_ENABLE_TELEMETRY=1
export OTEL_LOGS_EXPORTER=otlp
export OTEL_METRICS_EXPORTER=none          # AiSOC takes logs, not metrics
export OTEL_EXPORTER_OTLP_PROTOCOL=http/json
export OTEL_EXPORTER_OTLP_LOGS_ENDPOINT="${INGEST}/v1/logs"
export OTEL_EXPORTER_OTLP_HEADERS="X-Inbox-Token=${OTLP_TOKEN}"
export OTEL_LOGS_EXPORT_INTERVAL=2000
export OTEL_LOG_TOOL_DETAILS=1             # include Bash commands and file paths
export OTEL_LOG_USER_PROMPTS=1             # include prompt text (demo only; off by default for privacy)
export OTEL_SERVICE_NAME=claude-code
export OTEL_RESOURCE_ATTRIBUTES="host.name=\$(hostname)"
ENV
note "done"

echo
echo "Next:"
echo "  1. Log in once (copy-paste login that works in Codespaces):"
echo "       BROWSER=true claude auth login"
echo "  2. Start Claude Code with telemetry on:"
echo "       source demo/claude-code.env && claude"
